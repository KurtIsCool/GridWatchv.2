import fs from 'node:fs';
import path from 'node:path';

const root=process.cwd();
const outDir=path.join(root,'cloudflare','src','data','generated');
const psa=JSON.parse(fs.readFileSync(path.join(root,'data','psa-iloilo-city-barangays.json'),'utf8'));
const feeders=JSON.parse(fs.readFileSync(path.join(root,'data','feeder-mapping.json'),'utf8'));

function normalize(value=''){
  return String(value).normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase()
    .replace(/&/g,' and ').replace(/\b(brgy|barangay)\b/g,' ')
    .replace(/[^a-z0-9]+/g,' ').trim().replace(/\s+/g,' ')
    .replace(/^sta\b/,'santa').replace(/^sto\b/,'santo').replace(/\blapaz\b/g,'la paz');
}

if(psa.city_psgc!=='0631000000'||psa.barangay_count!==180||psa.barangays?.length!==180){
  throw new Error('Cloudflare data build requires the exact 180-member Iloilo City PSA registry.');
}
if(feeders.city_psgc!==psa.city_psgc||!Array.isArray(feeders.feeders))throw new Error('Feeder data does not match the PSA city registry.');

const approvedAliases=new Map();
for(const feeder of feeders.feeders){
  for(const row of feeder.coverage||[]){
    if(row.match_status!=='EXPLICIT_ALIAS'||!row.barangay_psgc||!row.source_label)continue;
    const key=normalize(row.source_label), previous=approvedAliases.get(key);
    if(previous&&previous!==row.barangay_psgc)throw new Error(`Ambiguous approved alias ${row.source_label}.`);
    approvedAliases.set(key,row.barangay_psgc);
  }
}

fs.mkdirSync(outDir,{recursive:true});
const banner='// Generated by tools/build-cloudflare-data.mjs. Do not edit by hand.\n';
fs.writeFileSync(path.join(outDir,'psa.generated.js'),`${banner}export const PSA_REGISTRY = Object.freeze(${JSON.stringify(psa)});\nexport const APPROVED_BARANGAY_ALIASES = Object.freeze(${JSON.stringify(Object.fromEntries([...approvedAliases].sort()))});\n`);
fs.writeFileSync(path.join(outDir,'feeders.generated.js'),`${banner}export const FEEDER_REGISTRY = Object.freeze(${JSON.stringify(feeders)});\n`);
console.log(`Built Worker identity modules from ${psa.barangays.length} PSA barangays and ${feeders.feeders.length} feeder cards.`);
